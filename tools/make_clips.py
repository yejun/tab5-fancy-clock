#!/usr/bin/env python3
"""Embed the hourly-announcement audio as voice_clips.h.

The clips come from the Halo watch project (waveshare2): a synthesised two-note bell (make_chime.py) and the 24
spoken hours (make_voice.py, Gemini TTS). All are 16 kHz mono s16le.

    tools/make_clips.py [CLIP_DIR]      # default: ~/Work/waveshare2/main/clips
"""
import pathlib
import sys

RATE = 16000
ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else pathlib.Path.home() / "Work/waveshare2/main/clips")
OUT = ROOT / "voice_clips.h"


def array(name, data):
    if len(data) % 2:
        sys.exit(f"{name}: odd byte count")
    samples = [int.from_bytes(data[i:i + 2], "little", signed=True) for i in range(0, len(data), 2)]
    lines = [", ".join(str(s) for s in samples[i:i + 24]) for i in range(0, len(samples), 24)]
    return f"alignas(4) static const int16_t {name}[{len(samples)}] = {{\n" + ",\n".join(lines) + "\n};\n"


def main():
    names = ["chime"] + [f"hour_{h:02d}" for h in range(24)]
    parts = [f"// Generated by tools/make_clips.py from {SRC.name}/ (Halo watch project) - do not edit.\n"
             f"// {RATE} Hz mono signed 16-bit PCM: a two-note bell, then the spoken hour.\n"
             "#pragma once\n#include <stdint.h>\n\n",
             f"static constexpr uint32_t CLIP_RATE = {RATE};\n\n"]
    total = 0
    for n in names:
        data = (SRC / f"{n}.pcm").read_bytes()
        total += len(data)
        parts.append(array(f"clip_{n}", data))
    parts.append("\nstruct Clip { const int16_t* pcm; uint32_t n; };\n"
                 "static const Clip CLIP_CHIME = {clip_chime, sizeof(clip_chime) / 2};\n"
                 "static const Clip CLIP_HOUR[24] = {\n" +
                 "".join(f"  {{clip_hour_{h:02d}, sizeof(clip_hour_{h:02d}) / 2}},\n" for h in range(24)) + "};\n")
    OUT.write_text("".join(parts))
    print(f"{OUT}: {len(names)} clips, {total / 1024:.0f} KiB of audio, {total / 2 / RATE:.1f} s")


if __name__ == "__main__":
    main()
